// Generates supabase/seed.sql from src/lib/seed.ts  →  npm run db:seed-sql
import { writeFileSync } from "node:fs";
const seed = await import("../src/lib/seed.ts");
const c = seed.seedContent;

const q = (v) => {
  if (v === null || v === undefined) return "null";
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "number") return String(v);
  if (Array.isArray(v)) return v.length ? `array[${v.map(q).join(",")}]::text[]` : "'{}'::text[]";
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
};
const insert = (table, rows) => {
  if (!rows.length) return `-- ${table}: no rows\n`;
  const cols = Object.keys(rows[0]);
  const vals = rows.map((r) => `  (${cols.map((k) => q(r[k])).join(", ")})`).join(",\n");
  return `insert into public.${table} (${cols.join(", ")}) values\n${vals}\non conflict (id) do nothing;\n`;
};

let sql = "-- Generated by scripts/seed-sql.mjs — initial content. Run after schema.sql.\n\n";
sql += `insert into public.site_settings (id, data) values (1, ${q(c.settings)})\non conflict (id) do update set data = excluded.data;\n\n`;
for (const t of ["projects", "presence", "skills", "experience", "education", "achievements", "tools", "posts"]) sql += insert(t, c[t]) + "\n";
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("supabase/seed.sql written");
